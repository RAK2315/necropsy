"""Write the external samples with Pillow. Requirement 11.13 to 11.16.

The image size is fixed in advance at 64 x 48 and must not be changed after the engine has been run
on the files. Pillow's encoders write the sample bytes; this script only prepares the source pixels
and calls Image.save.

Run from anywhere: python tools/make_external_samples.py   (needs Pillow, a development dependency)
"""
import datetime
import platform
from pathlib import Path

import PIL
from PIL import Image

W, H = 64, 48                                    # fixed in advance
OUT = Path(__file__).resolve().parent.parent / "spike" / "samples" / "external"


def source_pixels() -> list:
    """Deterministic, asymmetric (so a vertical flip is visible), well under 256 distinct colours."""
    px = []
    cx, cy, r2 = 46, 12, 8 * 8                   # sun, upper right
    for y in range(H):
        row = []
        for x in range(W):
            if y >= 34:                          # ground: two flat bands with a dark post at the left
                c = (70, 110, 60) if y < 42 else (50, 82, 44)
                if 6 <= x < 9 and 24 <= y:
                    c = (60, 40, 30)
            else:                                # sky: 17 horizontal bands, darker toward the top
                c = (30 + 8 * (y // 2), 60 + 7 * (y // 2), 130 + 5 * (y // 2))
            if (x - cx) ** 2 + (y - cy) ** 2 <= r2:
                c = (250, 214, 90)
            if 6 <= x < 9 and 24 <= y < 34:      # the post stands on the ground, reaching into the sky
                c = (60, 40, 30)
            row.append(c)
        px.append(row)
    return px


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    px = source_pixels()
    flat = [c for row in px for c in row]
    colours = sorted(set(flat))
    assert len(colours) <= 256, len(colours)

    (OUT / "source.ppm").write_bytes(
        f"P6\n{W} {H}\n255\n".encode("ascii") + bytes(v for c in flat for v in c))

    rgb = Image.new("RGB", (W, H))
    rgb.putdata(flat)

    index = {c: i for i, c in enumerate(colours)}
    pal = Image.new("P", (W, H))
    pal.putpalette([v for c in colours for v in c] + [0] * (768 - 3 * len(colours)))
    pal.putdata([index[c] for c in flat])

    pal.save(OUT / "external_a", format="PCX")
    rgb.save(OUT / "external_b", format="TGA")
    tga_orientation_arg = "none (Pillow default)"
    descriptor = (OUT / "external_b").read_bytes()[17]
    if (descriptor >> 5) & 1:                    # bit 5 set means top-left; Requirement 11.13 wants bottom-left
        rgb.save(OUT / "external_b", format="TGA", orientation=-1)
        tga_orientation_arg = "orientation=-1 (needed: Pillow's default wrote bit 5 set)"
        descriptor = (OUT / "external_b").read_bytes()[17]

    readme = f"""# External samples

These two files were written by Pillow's PCX and TGA encoders, not by this project's code. They exist so that
the engine is tested against files it did not write itself.

| File | Format | Written with |
|---|---|---|
| `external_a` | PCX, 8 bits per pixel, one plane, 256-colour palette | `pal.save("external_a", format="PCX")`, `pal` is Pillow mode `P` |
| `external_b` | TGA, 24 bits per pixel, uncompressed | `rgb.save("external_b", format="TGA")`, `rgb` is Pillow mode `RGB`; orientation option: {tga_orientation_arg} |

- Tool: Pillow {PIL.__version__}, Python {platform.python_version()}, written {datetime.datetime.now(datetime.timezone.utc):%Y-%m-%d} (UTC).
- Source image: `source.ppm`, a binary PPM (`P6`), {W} x {H} pixels, {len(colours)} distinct colours. The size was fixed before
  the engine was run on these files. It is generated by `tools/make_external_samples.py` (a sky of 17 bands, a sun at the upper right,
  two ground bands and a post at the left, so a vertical flip is visible).
- The palettised PCX is lossless because the source has at most 256 colours: the script builds the palette from the source's
  distinct colours and Pillow writes it. The TGA is written from the same pixels as RGB.
- TGA image descriptor byte (offset 0x11) as written: `0x{descriptor:02X}`. Bit 5 is {"set, so the origin is top-left" if (descriptor >> 5) & 1 else "clear, so the origin is bottom-left and the rows are stored bottom to top"}.
- The files are committed unmodified. To regenerate: `pip install pillow` then `python tools/make_external_samples.py`.
  A different Pillow version may write different bytes.
- Pillow is a development dependency of that script only. It is not used by the engine, the web service or the deployment.
"""
    (OUT / "README.md").write_text(readme, encoding="utf-8", newline="\n")
    print("colours:", len(colours), "descriptor: 0x%02X" % descriptor)


if __name__ == "__main__":
    main()